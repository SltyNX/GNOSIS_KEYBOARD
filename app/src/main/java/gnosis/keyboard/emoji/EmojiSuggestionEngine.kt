    private val dynamicEmojiMap: MutableMap<String, List<String>> = HashMap(KEYWORD_MAP)

    @Synchronized
    fun init(context: Context) {
        try {
            context.assets.open("emoji_suggestion_dictionary.txt").use { stream ->
                BufferedReader(InputStreamReader(stream)).useLines { lines ->
                    for (line in lines) {
                        val trimmed = line.trim()
                        if (trimmed.isEmpty() || trimmed.startsWith("#")) continue
                        val parts = trimmed.split("\t")
                        if (parts.size >= 2) {
                            val keyword = parts[0].trim().lowercase(Locale.ROOT)
                            val emojis = parts[1].trim().split(Regex("\\s+")).filter { it.isNotEmpty() }
                            if (keyword.isNotEmpty() && emojis.isNotEmpty()) {
                                dynamicEmojiMap[keyword] = emojis
                            }
                        }
                    }
                }
            }
        } catch (_: Exception) {}
        for ((k, v) in KEYWORD_MAP) {
            val existing = dynamicEmojiMap[k]
            if (existing != null) {
                dynamicEmojiMap[k] = (v + existing).distinct()
            } else {
                dynamicEmojiMap[k] = v
            }
        }
    }

    fun getEmojiSuggestions(text: String, limit: Int = 1): List<String> {
        val clean = text.trim().lowercase(Locale.ROOT)
        if (clean.isEmpty()) return emptyList()

        fun matchOrNull(k: String): List<String>? = dynamicEmojiMap[k]?.take(limit)

        matchOrNull(clean)?.let { return it }

        if (clean.length > 4 && clean.endsWith("ies")) {
            val stem = clean.substring(0, clean.length - 3) + "y"
            matchOrNull(stem)?.let { return it }
        }

        if (clean.length > 4 && clean.endsWith("ves")) {
            val stem = clean.substring(0, clean.length - 3)
            matchOrNull(stem + "fe")?.let { return it }
            matchOrNull(stem + "f")?.let { return it }
        }

        if (clean.length > 3 && clean.endsWith("es")) {
            val stem = clean.substring(0, clean.length - 2)
            matchOrNull(stem)?.let { return it }
        }

        if (clean.length > 2 && clean.endsWith("s")) {
            val stem = clean.substring(0, clean.length - 1)
            matchOrNull(stem)?.let { return it }
        }

        if (clean.length > 4 && clean.endsWith("ing")) {
            val base = clean.substring(0, clean.length - 3)
            matchOrNull(base)?.let { return it }
            matchOrNull(base + "e")?.let { return it }
            if (base.length > 2 && base[base.length - 1] == base[base.length - 2]) {
                matchOrNull(base.substring(0, base.length - 1))?.let { return it }
            }
        }

        if (clean.length > 3 && clean.endsWith("ed")) {
            val base = clean.substring(0, clean.length - 2)
            matchOrNull(base)?.let { return it }
            matchOrNull(base + "e")?.let { return it }
        }

        // 3. Prefix match if clean is at least 3 chars long (e.g. "hap" -> "happy", "lov" -> "love", "fir" -> "fire")
        if (clean.length >= 3) {
            for ((k, v) in dynamicEmojiMap) {
                if (k.startsWith(clean)) {
                    return v.take(limit)
                }
            }
        }

        return emptyList()
    }

    fun search(query: String, maxResults: Int = 45): List<String> {
        val q = query.trim().lowercase(Locale.ROOT)
        if (q.isEmpty()) return emptyList()
        val results = LinkedHashSet<String>()
        // 1. Direct key match
        dynamicEmojiMap[q]?.let { results.addAll(it) }
        // 2. Prefix matches on keys
        for ((k, v) in dynamicEmojiMap) {
            if (results.size >= maxResults) break
            if (k.startsWith(q)) {
                results.addAll(v)
            }
        }
        // 3. Substring matches on keys
        if (results.size < maxResults) {
            for ((k, v) in dynamicEmojiMap) {
                if (results.size >= maxResults) break
                if (k.contains(q)) {
                    results.addAll(v)
                }
            }
        }
        return results.take(maxResults)
    }
