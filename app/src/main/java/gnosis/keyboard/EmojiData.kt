    }

    private fun isEmojiRenderable(paint: Paint, emoji: String): Boolean {
        return try {
            if (paint.hasGlyph(emoji)) return true
            val stripped = emoji.replace("\uFE0F", "")
            if (stripped.isNotEmpty() && !stripped.contains('\u200D') && paint.hasGlyph(stripped)) {
                return true
            }
            false
        } catch (_: Exception) {
            true
        }
    }
